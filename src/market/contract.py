"""The contract of the Talent publication (B2, #878): what the app reads of ``talent-data`` before it opens a sealed file, declared ONCE.

Same idea as ``local_data.contract`` (the one of ``web-data``) and the same checker, but its own manifest: one entry per competition and season (not per collection) and its own schema,
because it is published in its own branch by its own workflow. ``python run_web_contract.py`` writes ``frontend/src/market/contract.generated.ts`` (the shared ``Wrap`` and ``FileEntry``
are imported from the one of ``web-data``, not declared twice); a test fails when the file is behind.
"""
# no ``from __future__ import annotations``: with postponed annotations a TypedDict cannot see which keys are ``NotRequired``
from typing import Any, List, Literal, NotRequired, TypedDict, get_type_hints

from src.local_data.contract import ContractError, FileEntry, Wrap, _check, _ts_type

TALENT_SCHEMA = 1


class TalentCompetitionEntry(FileEntry):
    """The sealed rows of a competition and season (``players/``): one row per player, team and competition; the groups and phases of the competition are inside."""
    key: str
    league: Literal["feb", "fbcyl"]
    competition: str
    season: str
    season_label: str
    players: int
    groups: List[str]
    wraps: List[Wrap]
    gender: NotRequired[Literal["F", "M"]]
    level: NotRequired[int]
    category: NotRequired[Literal["senior", "formacion"]]                      # #914: from the catalogue; absent when it does not know the competition
    age_group: NotRequired[Literal["U14", "U16", "U18", "U20"]]                  # only in formacion
    competition_label: NotRequired[str]                                          # the name people read (the youth codes of FEB are not)


class TalentManifest(TypedDict):
    """``index.json`` of the ``talent-data`` branch: the only file that keeps its name. ``v`` and ``open_key`` are those of the live packages' index (the key of the ``abierto`` scope)."""
    schema: int
    kind: Literal["talent"]
    v: int
    open_key: NotRequired[str]
    competitions: List[TalentCompetitionEntry]


MODELS = (TalentCompetitionEntry, TalentManifest)


def validate_talent_manifest(manifest: Any) -> None:
    """Raise ``ContractError`` unless ``manifest`` is a ``TalentManifest`` of the current ``TALENT_SCHEMA``."""
    _check(manifest, TalentManifest, "manifest")
    if manifest["schema"] != TALENT_SCHEMA:
        raise ContractError(f"manifest.schema: {manifest['schema']} is not the schema {TALENT_SCHEMA} of this contract")


def render_typescript() -> str:
    out = ["// AUTO-GENERATED by run_web_contract.py from src/market/contract.py: do not edit (a test fails when it is behind).",
           f"// The shape of what BasketLab Talent reads of `talent-data` before it opens a sealed file (epic #872). Schema {TALENT_SCHEMA}.", "",
           "import type { FileEntry, Wrap } from '@/webdata/contract.generated'", "", f"export const TALENT_SCHEMA = {TALENT_SCHEMA}", ""]
    for model in MODELS:
        out.append(f"/** {(model.__doc__ or '').strip()} */")
        out.append(f"export interface {model.__name__}{' extends FileEntry' if model is TalentCompetitionEntry else ''} {{")
        for key, hint in get_type_hints(model).items():
            if model is TalentCompetitionEntry and key in FileEntry.__annotations__:
                continue
            out.append(f"  {key}{'' if key in model.__required_keys__ else '?'}: {_ts_type(hint)}")
        out += ["}", ""]
    return "\n".join(out).replace("kind: string", "kind: 'talent'")
